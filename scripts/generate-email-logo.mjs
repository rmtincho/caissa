/**
 * Builds the Caissa email header as a single baked image: the white wordmark
 * (public/logo-caissa.svg) centered on a solid black band, exported as a base64
 * PNG in src/lib/email/logo.ts.
 *
 * Why a baked band instead of a transparent logo on a CSS-black <td>: dark-mode
 * email clients (Gmail, Apple Mail) recolor element backgrounds but never the
 * pixels inside an image. Baking the black into the image keeps the header black
 * and the wordmark visible everywhere — no white-on-white in dark mode.
 *
 * The template embeds it inline via `cid:caissa-logo`, so it renders without any
 * external host. Re-run only if the logo changes:
 *   pnpm add -D sharp && node scripts/generate-email-logo.mjs && pnpm remove sharp
 */
import { readFile, writeFile, mkdir } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import sharp from "sharp";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const svgPath = resolve(root, "public/logo-caissa.svg");
const outTs = resolve(root, "src/lib/email/logo.ts");

// Band displayed at 600×100; rendered @2x for retina email clients.
const BAND_W = 1200;
const BAND_H = 200;
const WORDMARK_W = 320; // ~160px on display — matches the site's hero scale.

const svg = await readFile(svgPath);

const wordmark = await sharp(svg, { density: 600 })
  .resize({ width: WORDMARK_W })
  .png()
  .toBuffer();

const band = await sharp({
  create: {
    width: BAND_W,
    height: BAND_H,
    channels: 4,
    background: { r: 0, g: 0, b: 0, alpha: 1 }, // solid black
  },
})
  .composite([{ input: wordmark, gravity: "center" }])
  .png()
  .toBuffer();

const base64 = band.toString("base64");

const file = `// AUTO-GENERATED by scripts/generate-email-logo.mjs — do not edit by hand.
// Caissa email header: white wordmark baked onto a solid black band (600×100),
// embedded as an inline cid: attachment so it renders correctly even in
// dark-mode email clients (which recolor backgrounds but not image pixels).

export const CAISSA_EMAIL_HEADER_PNG_BASE64 =
  "${base64}";
`;

await mkdir(dirname(outTs), { recursive: true });
await writeFile(outTs, file, "utf8");

console.log(
  `Wrote ${outTs} (${(base64.length / 1024).toFixed(1)} KB base64, ${band.length} bytes PNG)`,
);
